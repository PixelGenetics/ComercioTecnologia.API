/* ============================== 2. VISTA ================================== */
/* Contrato de lectura de la tienda (security_invoker requiere PostgreSQL 15+,
   que es lo que usa Supabase).                                                */
CREATE VIEW vw_catalogo WITH (security_invoker = true) AS
SELECT  p.id AS producto_id, p.nombre AS producto, v.id AS variante_id, v.sku,
        v.nombre_variante, p.marca, c.nombre AS categoria,
        v.precio, v.precio_comparacion,
        COALESCE(s.stock_total, 0) AS stock_total,
        p.garantia_meses
FROM    productos p
JOIN    variantes_producto v ON v.producto_id = p.id AND v.activo
JOIN    categorias c         ON c.id = p.categoria_id
LEFT JOIN LATERAL (SELECT SUM(i.cantidad)::int AS stock_total
                   FROM inventario_stock i WHERE i.variante_id = v.id) s ON TRUE
WHERE   p.activo;

