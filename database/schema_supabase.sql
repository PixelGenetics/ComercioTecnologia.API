/* Crear pedido desde el carrito. Devuelve el id del pedido. Los errores
   conservan los códigos originales (SQLSTATE 50001..50005); en Npgsql:
   PostgresException.SqlState.
   Uso:  SELECT fn_crear_pedido_desde_carrito(@u, @d, @e, @pago, @cupon, 0.15)   */
CREATE OR REPLACE FUNCTION fn_crear_pedido_desde_carrito(
    p_usuario_id         INT,
    p_direccion_envio_id INT,
    p_metodo_envio_id    INT,
    p_metodo_pago        VARCHAR,
    p_codigo_cupon       VARCHAR DEFAULT NULL,
    p_tasa_impuesto      NUMERIC DEFAULT 0.15
) RETURNS INT
LANGUAGE plpgsql
AS $$
DECLARE
    v_items     INT;
    v_sin_stock INT;
    v_subtotal  NUMERIC(12,2);
    v_envio     NUMERIC(10,2);
    v_cupon_id  INT;
    v_descuento NUMERIC(12,2) := 0;
    v_impuesto  NUMERIC(12,2);
    v_total     NUMERIC(12,2);
    v_pedido_id INT;
BEGIN
    SELECT COUNT(*),
           SUM(i.cantidad * v.precio),
           COALESCE(SUM(CASE WHEN COALESCE(s.total, 0) < i.cantidad THEN 1 ELSE 0 END), 0)
      INTO v_items, v_subtotal, v_sin_stock
      FROM items_usuario i
      JOIN variantes_producto v ON v.id = i.variante_id
      LEFT JOIN LATERAL (SELECT SUM(k.cantidad) AS total
                         FROM inventario_stock k WHERE k.variante_id = i.variante_id) s ON TRUE
     WHERE i.usuario_id = p_usuario_id AND i.lista = 'Carrito';

    IF v_items = 0 THEN
        RAISE EXCEPTION 'El carrito está vacío.' USING ERRCODE = '50001';
    END IF;

    IF NOT EXISTS (SELECT 1 FROM direcciones
                   WHERE id = p_direccion_envio_id AND usuario_id = p_usuario_id) THEN
        RAISE EXCEPTION 'La dirección no pertenece al usuario.' USING ERRCODE = '50002';
    END IF;

    IF v_sin_stock > 0 THEN
        RAISE EXCEPTION 'Stock insuficiente para uno o más productos.' USING ERRCODE = '50003';
    END IF;

    SELECT costo_base INTO v_envio FROM metodos_envio WHERE id = p_metodo_envio_id AND activo;
    IF v_envio IS NULL THEN
        RAISE EXCEPTION 'Método de envío no válido.' USING ERRCODE = '50005';
    END IF;

    IF p_codigo_cupon IS NOT NULL THEN
        -- Valida e incrementa usos en un único UPDATE atómico
        UPDATE cupones_descuento
           SET usos_actuales = usos_actuales + 1
         WHERE codigo = p_codigo_cupon
           AND activo
           AND (fecha_inicio IS NULL OR fecha_inicio <= now())
           AND fecha_expiracion >= now()
           AND (limite_uso IS NULL OR usos_actuales < limite_uso)
           AND monto_minimo <= v_subtotal
        RETURNING id,
                  CASE WHEN tipo = 'porcentaje' THEN ROUND(v_subtotal * valor / 100, 2)
                       WHEN valor > v_subtotal  THEN v_subtotal
                       ELSE valor END
          INTO v_cupon_id, v_descuento;

        IF v_cupon_id IS NULL THEN
            RAISE EXCEPTION 'El cupón no es válido o ya expiró.' USING ERRCODE = '50004';
        END IF;
    END IF;

    v_impuesto := ROUND((v_subtotal - v_descuento) * p_tasa_impuesto, 2);
    v_total    := v_subtotal - v_descuento + v_impuesto + v_envio;

    INSERT INTO pedidos (usuario_id, direccion_envio_id, metodo_envio_id, cupon_id, estado,
                         subtotal, descuento, impuesto, costo_envio, total, metodo_pago)
    VALUES (p_usuario_id, p_direccion_envio_id, p_metodo_envio_id, v_cupon_id, 'Pendiente',
            v_subtotal, v_descuento, v_impuesto, v_envio, v_total, p_metodo_pago)
    RETURNING id INTO v_pedido_id;

    INSERT INTO detalles_pedido (pedido_id, variante_id, cantidad, precio_unitario)
    SELECT v_pedido_id, i.variante_id, i.cantidad, v.precio
      FROM items_usuario i
      JOIN variantes_producto v ON v.id = i.variante_id
     WHERE i.usuario_id = p_usuario_id AND i.lista = 'Carrito';

    INSERT INTO eventos (entidad, entidad_id, tipo, titulo, detalle, usuario_id)
    VALUES ('pedido', v_pedido_id, 'Estado', 'Pendiente', 'Pedido creado desde el carrito', p_usuario_id);

    DELETE FROM items_usuario WHERE usuario_id = p_usuario_id AND lista = 'Carrito';

    RETURN v_pedido_id;
END;
$$;

